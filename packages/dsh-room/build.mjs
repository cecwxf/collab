// 1) Host half: protocol + sdk + lan-relay bundled into one ESM file.
// 2) Browser half: Rooms UI as a dsh client bundle — CJS factory wrapped in
//    window.__ModuleLoader__.load (registers under @collab/dsh-room and collab).
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  packages: "bundle",
  external: ["node:*", "ws", "multicast-dns", "bufferutil", "utf-8-validate"],
  banner: { js: "// dsh-room bundle — generated by build.mjs" },
  logLevel: "warning",
});

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const out = await build({
  entryPoints: ["src/client/index.jsx"],
  bundle: true,
  write: false,
  platform: "browser",
  format: "cjs",
  target: "es2022",
  jsx: "automatic",
  loader: { ".css": "text" },
  external: ["react", "react/jsx-runtime", "react-dom", "@deepseek-ai/dsh-client-ui-primitives"],
  legalComments: "inline",
  logLevel: "warning",
});
const code = out.outputFiles[0].text;
const ids = [pkg.name, "collab"];
const blocks = ids
  .map(
    (id) => `window.__ModuleLoader__.load({
\tid: ${JSON.stringify(id)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${code}
\t\treturn module.exports;
\t}
});`,
  )
  .join("\n");
writeFileSync(
  "dist/client.js",
  `// dsh-room Rooms UI client bundle — generated by build.mjs\n${blocks}\n`,
);
console.log(`bundled dist/index.js + dist/client.js (${(code.length / 1024).toFixed(1)} KiB, ids=${ids.join(",")})`);
