// 1) Host half: protocol + sdk bundled into one dependency-free ESM file (no registry needed for `dsh plugin add <path>`).
// 2) Browser half: the Rooms UI as a dsh client bundle — CJS factory wrapped in window.__ModuleLoader__.load,
//    resolving react / react/jsx-runtime / dsh-client-ui-primitives against dsh's PLATFORM_MODULES table.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  packages: "bundle",
  // ws / multicast-dns use CJS require("events"); keep them external (runtime deps).
  external: ["node:*", "ws", "multicast-dns", "bufferutil", "utf-8-validate"],
  banner: { js: "// dsh-room bundle — generated by build.mjs" },
  logLevel: "warning",
});

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const out = await build({
  entryPoints: ["src/client/index.jsx"],
  bundle: true,
  write: false,
  platform: "browser",
  format: "cjs",
  target: "es2022",
  jsx: "automatic",
  loader: { ".css": "text" },
  external: ["react", "react/jsx-runtime", "react-dom", "@deepseek-ai/dsh-client-ui-primitives"],
  legalComments: "inline",
  logLevel: "warning",
});
const code = out.outputFiles[0].text;
writeFileSync(
  "dist/client.js",
  `// dsh-room Rooms UI client bundle — generated by build.mjs\nwindow.__ModuleLoader__.load({\n\tid: ${JSON.stringify(pkg.name)},\n\tfactory: (require) => {\n\t\tvar module = { exports: {} };\n\t\tvar exports = module.exports;\n${code}\n\t\treturn module.exports;\n\t}\n});\n`,
);
console.log(`bundled dist/index.js + dist/client.js (${(code.length / 1024).toFixed(1)} KiB)`);
