// Bundle protocol + sdk into one dependency-free ESM file, so `dsh plugin add <path>` needs no registry.
import { build } from "esbuild";
await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  packages: "bundle",
  external: ["node:*"],
  banner: { js: "// dsh-collab bundle — generated by build.mjs" },
  logLevel: "warning",
});
console.log("bundled dist/index.js");
